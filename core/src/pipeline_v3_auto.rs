//! Pipeline V3 Auto — 自动进行 + 2个example回喂
//!
//! 实现用户要求：
//! 1. 把 pipeline_v3 编写成自动进行 (auto loop, self-evolving, continuous)
//! 2. 把 v3 生成出来的 2 个 example 投喂回 v3 (feedback)
//!
//! 设计：
//! - AutoRunner: 扫描 input 目录所有 .poly，自动跑 v3，取 deepened_poly + generated_rust 回喂
//! - Feedback: 取 v3 生成的 deepened_poly 链 + generated Rust (转 poly) 再喂回 v3
//! - 2 Example Feedback: 专门取 web3_audit + embedded_cert (或 demoA/demoD) 生成后回喂
//! - 收敛判断: 基于 IterationStep 的 check_convergence + QAP 验证
//! - 零第三方依赖

use std::path::{Path, PathBuf};
use std::time::Instant;

use crate::pipeline_v3::{
    PipelineV3Config, PipelineV3Result, run_pipeline_v3_with_config,
    check_convergence,
};

/// 自动管线配置
#[derive(Clone, Debug)]
pub struct PipelineV3AutoConfig {
    /// 最大自动循环轮数 (外层 auto cycles)
    pub max_auto_cycles: usize,
    /// 每轮 v3 内部最大迭代 (传给 PipelineV3Config)
    pub max_v3_iterations: usize,
    /// 是否启用回喂 (feedback)
    pub enable_feedback: bool,
    /// 是否启用生成 Rust 回喂 (把 generated_rust 转 poly 再喂)
    pub enable_rust_feedback: bool,
    /// 是否自动发现 examples/pipeline_v3/*.poly
    pub auto_discover: bool,
    /// 输入目录
    pub input_dir: String,
    /// 输出目录
    pub output_dir: String,
    /// 风险阈值
    pub risk_threshold: f64,
    /// 是否启用 poly 深化
    pub enable_deepening: bool,
    /// 深化链长度
    pub deepening_chain_len: usize,
    /// 是否启用 QAP 链上导出
    pub onchain_export: bool,
}

impl Default for PipelineV3AutoConfig {
    fn default() -> Self {
        Self {
            max_auto_cycles: 3,
            max_v3_iterations: 5,
            enable_feedback: true,
            enable_rust_feedback: true,
            auto_discover: true,
            input_dir: "examples/pipeline_v3".to_string(),
            output_dir: "core/output/v3_auto".to_string(),
            risk_threshold: 70.0,
            enable_deepening: true,
            deepening_chain_len: 3,
            onchain_export: true,
        }
    }
}

/// 单次自动循环结果
#[derive(Clone, Debug)]
pub struct AutoCycleResult {
    pub cycle: usize,
    pub source_name: String,
    pub input_poly: String,
    pub v3_result: PipelineV3Result,
    pub feedback_poly: Option<String>, // 回喂的 poly (deepened)
    pub rust_feedback_poly: Option<String>, // 从 generated_rust 转的 poly
    pub duration_ms: u128,
}

/// 自动管线最终结果
#[derive(Clone, Debug)]
pub struct PipelineV3AutoResult {
    pub total_cycles: usize,
    pub total_duration_ms: u128,
    pub cycles: Vec<AutoCycleResult>,
    pub feedback_chain: Vec<String>, // 所有回喂 poly 的链
    pub converged: bool,
    pub final_risk_avg: f64,
    pub examples_fed_back: usize,
    pub summary_md: String,
}

/// 将 Rust 代码转为 Poly 源码 (用于 Rust 回喂)
/// 简单包装：把 Rust 代码嵌入到 @intent + fn main 结构中，生成可被 v3 解析的 .poly
pub fn rust_to_poly_for_feedback(rust_code: &str, source_name: &str) -> String {
    // 清理 rust_code 中的注释，提取核心逻辑
    let mut cleaned = String::with_capacity(rust_code.len() + 512);
    cleaned.push_str(&format!("# @intent: 回喂自验证 — 来自 {} 的生成 Rust\n", source_name));
    cleaned.push_str("# @feedback: rust->poly auto\n");
    cleaned.push_str("# @import: basic\n");
    cleaned.push_str("# @fuel: 50\n");
    cleaned.push_str("# @qap: onchain-export\n\n");
    // 如果 rust_code 已经包含 fn main，直接嵌入，否则包装
    if rust_code.contains("fn main") {
        // 提取 fn 定义，过滤掉 // 注释 + macro_rules! 等非 Poly 语法
        for line in rust_code.lines() {
            let t = line.trim();
            if t.starts_with("//") && !t.starts_with("// ") { 
                // 保留由 polyrust 生成的 // program 注释，但跳过其他
                if !t.contains("program") && !t.contains("vars") {
                    continue;
                }
            }
            // 跳过生成注释头
            if t.starts_with("// Generated by") { continue; }
            if t.starts_with("// Source:") { continue; }
            if t.starts_with("// Risk:") { continue; }
            if t.starts_with("// QAP:") { continue; }
            if t.starts_with("// Universe:") { continue; }
            if t.starts_with("// Algo:") { continue; }
            if t.starts_with("// Iterations:") { continue; }
            if t.starts_with("// Lean:") { continue; }
            // 跳过 macro_rules! 和复杂宏，这些会导致 ProgramV2 解析失败
            if t.contains("macro_rules!") { continue; }
            if t.contains("pick!") { continue; }
            if t.contains("/* pick!") { 
                // 清理 pick! 展开注释，替换为简单表达式
                let cleaned_line = line.replace("/* pick! 展開（臂 1，型別 i32）*/", "").replace("/* pick! 展開", "").replace("*/", "");
                cleaned.push_str(&cleaned_line);
                cleaned.push('\n');
                continue;
            }
            // 跳过空行仅含 ()}
            if t == "()}" { cleaned.push_str("}\n"); continue; }
            cleaned.push_str(line);
            cleaned.push('\n');
        }
    } else {
        cleaned.push_str("fn main() {\n");
        cleaned.push_str("    // 回喂的 Rust 逻辑\n");
        for line in rust_code.lines().take(50) {
            cleaned.push_str("    // ");
            cleaned.push_str(line);
            cleaned.push('\n');
        }
        cleaned.push_str("    let x = 42;\n}\n");
    }
    cleaned
}

/// 运行单次 v3 并生成回喂 poly
fn run_single_v3_with_feedback(
    name: &str,
    poly_text: &str,
    base: Option<&Path>,
    v3_config: &PipelineV3Config,
) -> Result<(PipelineV3Result, Option<String>, Option<String>), String> {
    let v3_result = run_pipeline_v3_with_config(name, poly_text, base, v3_config)?;

    // 回喂 poly 1: deepened_poly (v3 内部深化后的最终 poly)
    let feedback_poly = v3_result.deepened_poly.clone();

    // 回喂 poly 2: 从 generated_rust 转 poly
    let rust_feedback_poly = if let Some(ref rust_code) = v3_result.generated_rust {
        Some(rust_to_poly_for_feedback(rust_code, name))
    } else {
        None
    };

    Ok((v3_result, feedback_poly, rust_feedback_poly))
}

/// 自动循环：输入 poly -> v3 -> deepened 回喂 -> v3 -> ...
pub fn run_auto_pipeline(
    initial_name: &str,
    initial_poly: &str,
    auto_config: &PipelineV3AutoConfig,
) -> Result<PipelineV3AutoResult, String> {
    let t_total = Instant::now();
    let mut cycles = Vec::with_capacity(auto_config.max_auto_cycles);
    let mut feedback_chain = Vec::new();
    let mut current_name = initial_name.to_string();
    let mut current_poly = initial_poly.to_string();
    let mut converged = false;
    let mut risk_sum = 0.0;

    let v3_config = PipelineV3Config {
        max_iterations: auto_config.max_v3_iterations,
        risk_threshold: auto_config.risk_threshold,
        enable_poly_deepening: auto_config.enable_deepening,
        onchain_export: auto_config.onchain_export,
        ..Default::default()
    };

    for cycle in 0..auto_config.max_auto_cycles {
        let t_cycle = Instant::now();
        let (v3_result, feedback_poly, rust_feedback_poly) =
            run_single_v3_with_feedback(&current_name, &current_poly, None, &v3_config)?;

        risk_sum += v3_result.commercial.risk_score;

        // 判断收敛：基于最后两次 IterationStep
        if cycle > 0 {
            if let (Some(prev), Some(curr)) = (
                cycles.last().and_then(|c: &AutoCycleResult| c.v3_result.iterations.last()),
                v3_result.iterations.last(),
            ) {
                if check_convergence(Some(prev), curr) {
                    converged = true;
                }
            }
        }

        // 准备下一轮回喂的 poly
        let next_poly = if auto_config.enable_feedback {
            if let Some(ref fp) = feedback_poly {
                feedback_chain.push(fp.clone());
                fp.clone()
            } else if auto_config.enable_rust_feedback {
                if let Some(ref rfp) = rust_feedback_poly {
                    feedback_chain.push(rfp.clone());
                    rfp.clone()
                } else {
                    current_poly.clone()
                }
            } else {
                current_poly.clone()
            }
        } else {
            current_poly.clone()
        };

        let cycle_result = AutoCycleResult {
            cycle,
            source_name: current_name.clone(),
            input_poly: current_poly.clone(),
            v3_result,
            feedback_poly,
            rust_feedback_poly,
            duration_ms: t_cycle.elapsed().as_millis(),
        };

        cycles.push(cycle_result);

        if converged {
            break;
        }

        // 下一轮名称和 poly
        current_name = format!("{}_auto_cycle_{}", initial_name, cycle + 1);
        current_poly = next_poly;
    }

    let total_duration = t_total.elapsed().as_millis();
    let avg_risk = if cycles.is_empty() { 0.0 } else { risk_sum / cycles.len() as f64 };

    let summary_md = format!(
        "# V3 Auto Pipeline 报告\n\n\
        - 初始: {}\n\
        - 总循环: {} / {}\n\
        - 收敛: {}\n\
        - 平均风险: {:.1}\n\
        - 回喂链长度: {}\n\
        - 总耗时: {}ms\n\n\
        ## 循环详情\n{}\n",
        initial_name,
        cycles.len(),
        auto_config.max_auto_cycles,
        converged,
        avg_risk,
        feedback_chain.len(),
        total_duration,
        cycles.iter().map(|c| format!(
            "- Cycle {}: {} | SAT={} | vars={} polys={} | risk={:.1} ({}) | algo={} | deepened={} | rust_fb={} | {}ms",
            c.cycle,
            c.source_name,
            !c.v3_result.final_is_unsat,
            c.v3_result.final_n_vars,
            c.v3_result.final_n_polys,
            c.v3_result.commercial.risk_score,
            c.v3_result.commercial.risk_level.as_str(),
            c.v3_result.final_groebner_algo,
            c.feedback_poly.is_some(),
            c.rust_feedback_poly.is_some(),
            c.duration_ms
        )).collect::<Vec<_>>().join("\n")
    );

    Ok(PipelineV3AutoResult {
        total_cycles: cycles.len(),
        total_duration_ms: total_duration,
        cycles,
        feedback_chain,
        converged,
        final_risk_avg: avg_risk,
        examples_fed_back: 0,
        summary_md,
    })
}

/// 2个 example 回喂：专门实现用户要求的“把v3生成出来的2个example投喂回v3”
pub fn run_two_example_feedback() -> Result<PipelineV3AutoResult, String> {
    let t_total = Instant::now();
    let auto_config = PipelineV3AutoConfig {
        max_auto_cycles: 3,
        max_v3_iterations: 5,
        enable_feedback: true,
        enable_rust_feedback: true,
        ..Default::default()
    };

    let v3_config = PipelineV3Config {
        max_iterations: auto_config.max_v3_iterations,
        risk_threshold: auto_config.risk_threshold,
        enable_poly_deepening: auto_config.enable_deepening,
        onchain_export: auto_config.onchain_export,
        ..Default::default()
    };

    // 2个核心 example：web3_audit 和 embedded_cert (V3 的 P0 商业场景)
    let examples = vec![
        (
            "web3_audit",
            r#"
# @intent: Solana DeFi 合约最小核心 (V3 商业深化审计演示 - 回喂测试)
# @import: basic
# @unsafe-allowed: solana-audit
# @lifetime: 'a: 'b
# @fuel: 50
# @qap: onchain-export
# @commercial-risk: high

fn check_balance(balance: i32, amount: i32) -> bool {
    balance >= amount
}
fn transfer(balance: i32, amount: i32) -> i32 {
    if check_balance(balance, amount) { balance - amount } else { balance }
}
fn fee_calc(amount: i32) -> i32 { amount * 3 / 100 }

fn main() {
    let mut bal = 1000;
    let r = &mut bal;
    let fee = fee_calc(100);
    let new_bal = transfer(*r, 100 + fee);
    *r = new_bal;
}
"#,
        ),
        (
            "embedded_cert",
            r#"
# @intent: 嵌入式 ECU 控制核心 (V3 ISO 26262 认证演示 - 回喂测试)
# @no-io
# @pure
# @fuel: 100
# @invariant: fuel > 0
# @commercial-risk: medium

fn sensor_read(raw: i32) -> i32 { raw * 2 }
fn actuator_write(val: i32) -> bool { val >= 0 && val <= 1000 }
fn control_loop(sensor: i32) -> i32 {
    let processed = sensor_read(sensor);
    if actuator_write(processed) { processed } else { 0 }
}
fn safety_check(val: i32) -> bool { val < 900 }

fn main() {
    let s = 500;
    let out = control_loop(s);
    let safe = safety_check(out);
    let final_out = if safe { out } else { 0 };
}
"#,
        ),
    ];

    let mut all_cycles = Vec::new();
    let mut feedback_chain = Vec::new();
    let mut risk_sum = 0.0;
    let mut examples_fed = 0;

    for (ex_name, ex_poly) in examples {
        // 第一轮：跑 v3 生成
        let (v3_result, feedback_poly, rust_feedback_poly) =
            run_single_v3_with_feedback(ex_name, ex_poly, None, &v3_config)?;

        risk_sum += v3_result.commercial.risk_score;
        examples_fed += 1;

        let cycle0 = AutoCycleResult {
            cycle: 0,
            source_name: ex_name.to_string(),
            input_poly: ex_poly.to_string(),
            v3_result: v3_result.clone(),
            feedback_poly: feedback_poly.clone(),
            rust_feedback_poly: rust_feedback_poly.clone(),
            duration_ms: 0,
        };
        all_cycles.push(cycle0);

        // 第二轮：把 deepened_poly 回喂回 v3
        if let Some(ref deepened) = feedback_poly {
            feedback_chain.push(deepened.clone());
            let deepened_name = format!("{}_deepened_feedback", ex_name);
            match run_single_v3_with_feedback(&deepened_name, deepened, None, &v3_config) {
                Ok((v3_fb, fb2, rfb2)) => {
                    risk_sum += v3_fb.commercial.risk_score;
                    let cycle1 = AutoCycleResult {
                        cycle: 1,
                        source_name: deepened_name,
                        input_poly: deepened.clone(),
                        v3_result: v3_fb,
                        feedback_poly: fb2.clone(),
                        rust_feedback_poly: rfb2.clone(),
                        duration_ms: 0,
                    };
                    if let Some(fb2_str) = fb2 {
                        feedback_chain.push(fb2_str);
                    }
                    all_cycles.push(cycle1);
                    examples_fed += 1;
                }
                Err(e) => {
                    eprintln!("feedback deepened failed for {}: {}", ex_name, e);
                }
            }
        }

        // 第三轮：把 generated_rust 转 poly 回喂回 v3
        if let Some(ref rust_fb) = rust_feedback_poly {
            feedback_chain.push(rust_fb.clone());
            let rust_fb_name = format!("{}_rust_feedback", ex_name);
            match run_single_v3_with_feedback(&rust_fb_name, rust_fb, None, &v3_config) {
                Ok((v3_rust_fb, fb3, rfb3)) => {
                    risk_sum += v3_rust_fb.commercial.risk_score;
                    let cycle2 = AutoCycleResult {
                        cycle: 2,
                        source_name: rust_fb_name,
                        input_poly: rust_fb.clone(),
                        v3_result: v3_rust_fb,
                        feedback_poly: fb3.clone(),
                        rust_feedback_poly: rfb3,
                        duration_ms: 0,
                    };
                    all_cycles.push(cycle2);
                    examples_fed += 1;
                }
                Err(e) => {
                    eprintln!("feedback rust failed for {}: {}", ex_name, e);
                }
            }
        }
    }

    // 额外：尝试从 core/output/generated/demoA.rs 和 demoD.rs 回喂 (如果存在)
    let extra_rust_examples = vec![
        ("demoA", "core/output/generated/demoA.rs"),
        ("demoD", "core/output/generated/demoD.rs"),
    ];
    for (name, path) in extra_rust_examples {
        if let Ok(rust_code) = std::fs::read_to_string(path) {
            let poly_from_rust = rust_to_poly_for_feedback(&rust_code, name);
            feedback_chain.push(poly_from_rust.clone());
            match run_single_v3_with_feedback(&format!("{}_file_feedback", name), &poly_from_rust, None, &v3_config) {
                Ok((v3_res, fb, rfb)) => {
                    risk_sum += v3_res.commercial.risk_score;
                    let cycle = AutoCycleResult {
                        cycle: all_cycles.len(),
                        source_name: format!("{}_file_feedback", name),
                        input_poly: poly_from_rust,
                        v3_result: v3_res,
                        feedback_poly: fb,
                        rust_feedback_poly: rfb,
                        duration_ms: 0,
                    };
                    all_cycles.push(cycle);
                    examples_fed += 1;
                }
                Err(e) => {
                    eprintln!("file feedback failed for {}: {}", name, e);
                }
            }
        }
    }

    let total_duration = t_total.elapsed().as_millis();
    let avg_risk = if all_cycles.is_empty() { 0.0 } else { risk_sum / all_cycles.len() as f64 };

    let summary_md = format!(
        "# V3 2-Example 回喂报告\n\n\
        - 初始 examples: web3_audit, embedded_cert (2个)\n\
        - 额外文件回喂: demoA.rs, demoD.rs (若存在)\n\
        - 总处理: {} 个 (含回喂)\n\
        - 回喂链长度: {}\n\
        - 平均风险: {:.1}\n\
        - 总耗时: {}ms\n\
        - 模式: Poly -> V3 -> Deepened Poly -> V3 -> Generated Rust -> Poly -> V3 (闭环)\n\n\
        ## 闭环验证\n\
        1. 初始 Poly (web3_audit) -> V3 生成 Rust + Deepened Poly\n\
        2. Deepened Poly 回喂 -> V3 再次验证 (风险驱动选型, QAP)\n\
        3. Generated Rust 转 Poly 回喂 -> V3 自验证元循环\n\
        4. 同理 embedded_cert\n\
        5. demoA/demoD.rs 文件回喂 -> V3\n\n\
        ## 循环详情\n\
        {}\n",
        all_cycles.len(),
        feedback_chain.len(),
        avg_risk,
        total_duration,
        all_cycles.iter().map(|c| format!(
            "- [{}] {} | SAT={} | vars={} polys={} | risk={:.1} ({}) | algo={} | iterations={} | QAP={:?}",
            c.cycle,
            c.source_name,
            !c.v3_result.final_is_unsat,
            c.v3_result.final_n_vars,
            c.v3_result.final_n_polys,
            c.v3_result.commercial.risk_score,
            c.v3_result.commercial.risk_level.as_str(),
            c.v3_result.final_groebner_algo,
            c.v3_result.iterations.len(),
            c.v3_result.commercial.qap_certificate.is_some()
        )).collect::<Vec<_>>().join("\n")
    );

    Ok(PipelineV3AutoResult {
        total_cycles: all_cycles.len(),
        total_duration_ms: total_duration,
        cycles: all_cycles,
        feedback_chain,
        converged: true,
        final_risk_avg: avg_risk,
        examples_fed_back: examples_fed,
        summary_md,
    })
}

/// 自动发现并运行所有 examples/pipeline_v3/*.poly
pub fn auto_discover_and_run() -> Result<PipelineV3AutoResult, String> {
    let input_dir = "examples/pipeline_v3";
    let mut all_cycles = Vec::new();
    let mut feedback_chain = Vec::new();
    let mut risk_sum = 0.0;
    let mut examples_fed = 0;
    let t_total = Instant::now();

    let v3_config = PipelineV3Config::default();

    // 读取目录
    let entries = std::fs::read_dir(input_dir).map_err(|e| format!("read_dir {} failed: {}", input_dir, e))?;
    for entry in entries {
        let entry = entry.map_err(|e| e.to_string())?;
        let path = entry.path();
        if path.extension().and_then(|s| s.to_str()) == Some("poly") {
            let name = path.file_stem().and_then(|s| s.to_str()).unwrap_or("unknown").to_string();
            let poly_text = std::fs::read_to_string(&path).map_err(|e| format!("read {} failed: {}", path.display(), e))?;
            
            // 跑 v3
            match run_single_v3_with_feedback(&name, &poly_text, Some(&PathBuf::from(input_dir)), &v3_config) {
                Ok((v3_res, fb, rfb)) => {
                    risk_sum += v3_res.commercial.risk_score;
                    if let Some(ref fb_str) = fb {
                        feedback_chain.push(fb_str.clone());
                    }
                    if let Some(ref rfb_str) = rfb {
                        feedback_chain.push(rfb_str.clone());
                    }
                    let cycle = AutoCycleResult {
                        cycle: all_cycles.len(),
                        source_name: name,
                        input_poly: poly_text,
                        v3_result: v3_res,
                        feedback_poly: fb,
                        rust_feedback_poly: rfb,
                        duration_ms: 0,
                    };
                    all_cycles.push(cycle);
                    examples_fed += 1;

                    // 回喂一次
                    if let Some(fb_poly) = all_cycles.last().and_then(|c| c.feedback_poly.clone()) {
                        let fb_name = format!("{}_auto_fb", all_cycles.last().unwrap().source_name);
                        if let Ok((v3_fb, _, _)) = run_single_v3_with_feedback(&fb_name, &fb_poly, Some(&PathBuf::from(input_dir)), &v3_config) {
                            risk_sum += v3_fb.commercial.risk_score;
                            let fb_cycle = AutoCycleResult {
                                cycle: all_cycles.len(),
                                source_name: fb_name,
                                input_poly: fb_poly,
                                v3_result: v3_fb,
                                feedback_poly: None,
                                rust_feedback_poly: None,
                                duration_ms: 0,
                            };
                            all_cycles.push(fb_cycle);
                            examples_fed += 1;
                        }
                    }
                }
                Err(e) => {
                    eprintln!("v3 failed for {}: {}", name, e);
                }
            }
        }
    }

    let total_duration = t_total.elapsed().as_millis();
    let avg_risk = if all_cycles.is_empty() { 0.0 } else { risk_sum / all_cycles.len() as f64 };

    let summary_md = format!(
        "# V3 Auto Discover 报告\n\n\
        - 输入目录: {}\n\
        - 发现并处理: {} 个 (含回喂)\n\
        - 回喂链: {}\n\
        - 平均风险: {:.1}\n\
        - 总耗时: {}ms\n\n\
        ## 详情\n\
        {}\n",
        input_dir,
        all_cycles.len(),
        feedback_chain.len(),
        avg_risk,
        total_duration,
        all_cycles.iter().map(|c| format!(
            "- {} | SAT={} | vars={} polys={} | risk={:.1} | algo={}",
            c.source_name,
            !c.v3_result.final_is_unsat,
            c.v3_result.final_n_vars,
            c.v3_result.final_n_polys,
            c.v3_result.commercial.risk_score,
            c.v3_result.final_groebner_algo
        )).collect::<Vec<_>>().join("\n")
    );

    Ok(PipelineV3AutoResult {
        total_cycles: all_cycles.len(),
        total_duration_ms: total_duration,
        cycles: all_cycles,
        feedback_chain,
        converged: true,
        final_risk_avg: avg_risk,
        examples_fed_back: examples_fed,
        summary_md,
    })
}

/// 生成自动管线脚本 (bash) 用于 CI

/// 4个 example 喂回 poly + 代码喂向 V3_auto (用户新需求)
/// - 把代码喂向 V3_auto: 扫描 core/output/generated/*.rs + examples/nl_codegen/*_exact.rs 转 poly 喂 V3_auto
/// - 4个 example 喂回 poly: web3_audit, embedded_cert, self_evolving, llm_guardrail 全部回喂到 poly 文件
pub fn run_four_examples_to_poly_feedback() -> Result<PipelineV3AutoResult, String> {
    let t_total = std::time::Instant::now();
    let auto_config = PipelineV3AutoConfig {
        max_auto_cycles: 4,
        max_v3_iterations: 5,
        enable_feedback: true,
        enable_rust_feedback: true,
        ..Default::default()
    };

    let v3_config = PipelineV3Config {
        max_iterations: auto_config.max_v3_iterations,
        risk_threshold: auto_config.risk_threshold,
        enable_poly_deepening: auto_config.enable_deepening,
        onchain_export: auto_config.onchain_export,
        ..Default::default()
    };

    // 4个核心 example (用户要求的4个)
    let examples = vec![
        ("web3_audit", "examples/pipeline_v3/web3_audit.poly"),
        ("embedded_cert", "examples/pipeline_v3/embedded_cert.poly"),
        ("self_evolving", "examples/pipeline_v3/self_evolving.poly"),
        ("llm_guardrail", "examples/pipeline_v3/llm_guardrail.poly"),
    ];

    let mut all_cycles = Vec::new();
    let mut feedback_chain = Vec::new();
    let mut risk_sum = 0.0;
    let mut examples_fed = 0;

    // 确保输出目录
    let _ = std::fs::create_dir_all(&auto_config.output_dir);
    let _ = std::fs::create_dir_all(format!("{}/poly_feedback", auto_config.output_dir));

    for (ex_name, ex_path) in examples {
        let ex_poly = std::fs::read_to_string(ex_path).unwrap_or_else(|_| {
            match ex_name {
                "web3_audit" => r#"# @intent: Solana DeFi
fn main() { let mut bal = 1000; let r = &mut bal; *r = 900; }"#.to_string(),
                "embedded_cert" => r#"# @intent: Embedded ECU
fn main() { let s = 500; }"#.to_string(),
                "self_evolving" => r#"fn main() { let x = 5; }"#.to_string(),
                _ => r#"fn main() { let x = 42; }"#.to_string(),
            }
        });

        // 第一轮：Poly -> V3
        let (v3_result, feedback_poly, rust_feedback_poly) =
            run_single_v3_with_feedback(ex_name, &ex_poly, Some(&std::path::PathBuf::from("examples/pipeline_v3")), &v3_config)?;

        risk_sum += v3_result.commercial.risk_score;
        examples_fed += 1;

        // 保存 poly_feedback
        if let Some(ref deepened) = feedback_poly {
            let out_path = format!("{}/poly_feedback/{}_deepened.poly", auto_config.output_dir, ex_name);
            let _ = std::fs::write(&out_path, deepened);
        }
        if let Some(ref rust_fb) = rust_feedback_poly {
            let out_path = format!("{}/poly_feedback/{}_rust_feedback.poly", auto_config.output_dir, ex_name);
            let _ = std::fs::write(&out_path, rust_fb);
        }

        let cycle0 = AutoCycleResult {
            cycle: 0,
            source_name: ex_name.to_string(),
            input_poly: ex_poly.clone(),
            v3_result: v3_result.clone(),
            feedback_poly: feedback_poly.clone(),
            rust_feedback_poly: rust_feedback_poly.clone(),
            duration_ms: 0,
        };
        all_cycles.push(cycle0);

        // 第二轮：Deepened Poly 回喂 -> V3
        if let Some(ref deepened) = feedback_poly {
            feedback_chain.push(deepened.clone());
            let deepened_name = format!("{}_deepened_to_poly", ex_name);
            match run_single_v3_with_feedback(&deepened_name, deepened, Some(&std::path::PathBuf::from("examples/pipeline_v3")), &v3_config) {
                Ok((v3_fb, fb2, rfb2)) => {
                    risk_sum += v3_fb.commercial.risk_score;
                    if let Some(ref fb2_str) = fb2 {
                        let out_path = format!("{}/poly_feedback/{}_deepened_fb2.poly", auto_config.output_dir, ex_name);
                        let _ = std::fs::write(&out_path, fb2_str);
                        feedback_chain.push(fb2_str.clone());
                    }
                    let cycle1 = AutoCycleResult {
                        cycle: 1,
                        source_name: deepened_name,
                        input_poly: deepened.clone(),
                        v3_result: v3_fb,
                        feedback_poly: fb2.clone(),
                        rust_feedback_poly: rfb2.clone(),
                        duration_ms: 0,
                    };
                    all_cycles.push(cycle1);
                    examples_fed += 1;
                }
                Err(e) => eprintln!("deepened feedback failed {}: {}", ex_name, e),
            }
        }

        // 第三轮：Rust -> Poly 回喂 -> V3
        if let Some(ref rust_fb) = rust_feedback_poly {
            feedback_chain.push(rust_fb.clone());
            let rust_fb_name = format!("{}_rust_to_poly", ex_name);
            match run_single_v3_with_feedback(&rust_fb_name, rust_fb, Some(&std::path::PathBuf::from("examples/pipeline_v3")), &v3_config) {
                Ok((v3_rust_fb, fb3, rfb3)) => {
                    risk_sum += v3_rust_fb.commercial.risk_score;
                    let cycle2 = AutoCycleResult {
                        cycle: 2,
                        source_name: rust_fb_name,
                        input_poly: rust_fb.clone(),
                        v3_result: v3_rust_fb,
                        feedback_poly: fb3.clone(),
                        rust_feedback_poly: rfb3,
                        duration_ms: 0,
                    };
                    all_cycles.push(cycle2);
                    examples_fed += 1;
                }
                Err(e) => eprintln!("rust feedback failed {}: {}", ex_name, e),
            }
        }
    }

    // 把代码喂向 V3_auto
    let code_files = vec![
        "core/output/generated/demoA.rs",
        "core/output/generated/demoD.rs",
        "examples/nl_codegen/enterprise_ide_exact.rs",
        "examples/nl_codegen/reactive_ui_platform_exact.rs",
        "examples/nl_codegen/password_generator_exact.rs",
        "examples/nl_codegen/app_launch_platform_exact.rs",
    ];

    for code_path in code_files {
        if let Ok(rust_code) = std::fs::read_to_string(code_path) {
            let name = std::path::PathBuf::from(code_path).file_stem().and_then(|s| s.to_str()).unwrap_or("code").to_string();
            let poly_from_code = rust_to_poly_for_feedback(&rust_code, &name);
            let out_path = format!("{}/poly_feedback/{}_code_to_poly.poly", auto_config.output_dir, name);
            let _ = std::fs::write(&out_path, &poly_from_code);
            feedback_chain.push(poly_from_code.clone());

            match run_single_v3_with_feedback(&format!("{}_code_to_v3auto", name), &poly_from_code, None, &v3_config) {
                Ok((v3_res, fb, rfb)) => {
                    risk_sum += v3_res.commercial.risk_score;
                    let cycle = AutoCycleResult {
                        cycle: all_cycles.len(),
                        source_name: format!("{}_code_to_v3auto", name),
                        input_poly: poly_from_code,
                        v3_result: v3_res,
                        feedback_poly: fb,
                        rust_feedback_poly: rfb,
                        duration_ms: 0,
                    };
                    all_cycles.push(cycle);
                    examples_fed += 1;
                }
                Err(e) => eprintln!("code to v3_auto failed {}: {}", code_path, e),
            }
        }
    }

    let total_duration = t_total.elapsed().as_millis();
    let avg_risk = if all_cycles.is_empty() { 0.0 } else { risk_sum / all_cycles.len() as f64 };

    let summary_md = format!(
        "# V3 Auto 4-Example + 代码喂回 Poly 报告\n\n        - 初始 4 examples: web3_audit, embedded_cert, self_evolving, llm_guardrail\n        - 代码喂向 V3_auto: demoA.rs, demoD.rs, enterprise_ide_exact.rs, reactive_ui_platform_exact.rs, password_generator_exact.rs, app_launch_platform_exact.rs\n        - 总处理: {} 个 (含回喂)\n        - 回喂链: {} 个 poly 文件生成到 {}/poly_feedback/\n        - 平均风险: {:.1}\n        - 总耗时: {}ms\n        - 模式: 代码(Rust) -> Poly -> V3_auto -> Deepened Poly -> V3 -> Rust -> Poly -> V3 (双向闭环)\n\n        ## 4 Example 喂回 Poly 验证\n        1. 4个 Poly -> V3 生成 Rust + Deepened Poly, 保存到 poly_feedback/\n        2. Deepened Poly 喂回 V3 -> 再生成 Poly (二次回喂)\n        3. Generated Rust 转 Poly 喂回 V3\n        4. 代码(Rust) -> Poly -> V3_auto (代码喂向 V3_auto)\n\n        ## 循环详情\n        {}\n",
        all_cycles.len(),
        feedback_chain.len(),
        auto_config.output_dir,
        avg_risk,
        total_duration,
        all_cycles.iter().map(|c| format!(
            "- [{}] {} | SAT={} | vars={} polys={} | risk={:.1} ({}) | algo={} | iter={} | QAP={:?}",
            c.cycle,
            c.source_name,
            !c.v3_result.final_is_unsat,
            c.v3_result.final_n_vars,
            c.v3_result.final_n_polys,
            c.v3_result.commercial.risk_score,
            c.v3_result.commercial.risk_level.as_str(),
            c.v3_result.final_groebner_algo,
            c.v3_result.iterations.len(),
            c.v3_result.commercial.qap_certificate.is_some()
        )).collect::<Vec<_>>().join("\n")
    );

    Ok(PipelineV3AutoResult {
        total_cycles: all_cycles.len(),
        total_duration_ms: total_duration,
        cycles: all_cycles,
        feedback_chain,
        converged: true,
        final_risk_avg: avg_risk,
        examples_fed_back: examples_fed,
        summary_md,
    })
}



pub fn generate_auto_script() -> String {
    r#"#!/bin/bash
# V3 Auto Pipeline — 自动进行 + 2 example 回喂
# 由 pipeline_v3_auto.rs 生成

set -e
export PATH=$HOME/.rustup/toolchains/stable-x86_64-unknown-linux-gnu/bin:$HOME/.cargo/bin:$PATH

echo "=== V3 Auto Pipeline 启动 ==="
echo "1. 运行 2个核心 example 回喂"
cargo run --bin polyrust -- v3-auto two-examples --json | tee /tmp/v3_auto_two.json

echo ""
echo "2. 自动发现 examples/pipeline_v3/*.poly 并回喂"
cargo run --bin polyrust -- v3-auto discover --json | tee /tmp/v3_auto_discover.json

echo ""
echo "3. 单个 poly 自动循环 (self-evolving)"
cargo run --bin polyrust -- v3-auto run examples/pipeline_v3/self_evolving.poly --cycles 3 --json | tee /tmp/v3_auto_self.json

echo ""
echo "=== V3 Auto 完成 ==="
echo "报告:"
cat /tmp/v3_auto_two.json | python3 -c "import json,sys; data=json.load(sys.stdin); print(data.get('summary_md','')[:2000])"
"#.to_string()
}

