#[cfg(test)]
mod tests {
    use super::*;
    use crate::qap::{R1cs, qap_from_r1cs};
    use crate::fp::Fp;

    #[test]
    fn test_groth16_dummy() {
        let r1cs = R1cs {
            n_wires: 4,
            constraints: vec![(vec![(1, Fp::one())], vec![(2, Fp::one())], vec![(3, Fp::one())])],
            intermediates: vec![None; 4],
        };
        let qap = qap_from_r1cs(&r1cs);
        let proof = groth16_from_r1cs(&r1cs, &qap);
        assert!(proof.verified);
        assert_eq!(proof.a.len(), 32);
        assert_eq!(proof.b.len(), 64);
        let json = proof.to_json().to_string();
        assert!(json.contains("groth16"));
        assert!(json.contains("bn128"));
        let ix = proof.to_solana_ix_data();
        assert!(ix.len() >= 129);
        let prog = generate_solana_groth16_verifier(&proof);
        assert!(prog.contains("Groth16Proof"));
        assert!(prog.contains("Polyrust.Groth16"));
    }

    #[test]
    fn test_groth16_pipeline() {
        let r1cs = R1cs {
            n_wires: 3,
            constraints: vec![(vec![(1, Fp::one())], vec![(2, Fp::one())], vec![(0, Fp::one())])],
            intermediates: vec![None; 3],
        };
        let qap = qap_from_r1cs(&r1cs);
        let (proof, json, program, ix) = run_groth16_pipeline(&r1cs, &qap);
        assert!(proof.verified);
        assert!(json.contains("r1cs_hash"));
        assert!(program.contains("verify"));
        assert!(!ix.is_empty());
    }
}
