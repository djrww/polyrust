/// 生成 TypeScript 客戶端
pub fn generate_ts_client(payload: &SolanaQapPayload) -> String {
    format!(r#"// Solana QAP Verifier Client — TypeScript
// Source: {source} | Risk: {risk:.1} | QAP: {qap}
// Auto-generated by polyrust v3

import {{ Connection, PublicKey, Keypair, SystemProgram, Transaction, TransactionInstruction }} from "@solana/web3.js";
import * as anchor from "@coral-xyz/anchor";

export const PROGRAM_ID = new PublicKey("PolyRuSTQAP1111111111111111111111111111111");

export interface QapCertificate {{
  sourceName: string;
  r1csConstraints: anchor.BN;
  r1csWires: anchor.BN;
  riskScore: anchor.BN;
  qapVerified: boolean;
  timestamp: anchor.BN;
  certificateHash: number[];
}}

export async function verifyQapOnChain(
  connection: Connection,
  authority: Keypair,
  cert: QapCertificate
): Promise<string> {{
  console.log(`Verifying QAP for ${{cert.sourceName}}: constraints=${{cert.r1csConstraints}} wires=${{cert.r1csWires}} risk=${{cert.riskScore}}`);

  // 創建證書賬戶
  const certAccount = Keypair.generate();
  const lamports = await connection.getMinimumBalanceForRentExemption(128);

  const createAccountIx = SystemProgram.createAccount({{
    fromPubkey: authority.publicKey,
    newAccountPubkey: certAccount.publicKey,
    lamports,
    space: 128,
    programId: PROGRAM_ID,
  }});

  // 構造 verify_qap 指令數據
  const data = Buffer.alloc(33);
  data.writeBigUInt64LE(BigInt(cert.r1csConstraints.toString()), 0);
  data.writeBigUInt64LE(BigInt(cert.r1csWires.toString()), 8);
  data.writeBigUInt64LE(BigInt(cert.riskScore.toString()), 16);
  data.writeUInt8(cert.qapVerified ? 1 : 0, 24);
  data.writeBigInt64LE(BigInt(cert.timestamp.toString()), 25);

  const verifyIx = new TransactionInstruction({{
    keys: [
      {{ pubkey: authority.publicKey, isSigner: true, isWritable: false }},
      {{ pubkey: certAccount.publicKey, isSigner: false, isWritable: true }},
      {{ pubkey: SystemProgram.programId, isSigner: false, isWritable: false }},
    ],
    programId: PROGRAM_ID,
    data,
  }});

  const tx = new Transaction().add(createAccountIx, verifyIx);
  const sig = await anchor.web3.sendAndConfirmTransaction(connection, tx, [authority, certAccount]);
  
  console.log(`QAP verified on-chain: ${{sig}} for ${{cert.sourceName}}`);
  console.log(`Risk: {risk:.1} ({risk_level}) | QAP: {qap} | Lean: Polyrust.Bidirectional7Files.seven_files_all_pass`);
  
  return sig;
}}

export async function auditContract(
  sourceName: string = "{source}",
  riskScore: number = {risk},
  qapVerified: boolean = {qap}
) {{
  const connection = new Connection("https://api.devnet.solana.com", "confirmed");
  const authority = Keypair.generate(); // 實際應從錢包加載
  
  const cert: QapCertificate = {{
    sourceName,
    r1csConstraints: new anchor.BN({constraints}),
    r1csWires: new anchor.BN({wires}),
    riskScore: new anchor.BN({risk_int}),
    qapVerified,
    timestamp: new anchor.BN({timestamp}),
    certificateHash: Array(32).fill(0xAB),
  }};

  const sig = await verifyQapOnChain(connection, authority, cert);
  return {{ signature: sig, certificate: cert, source: sourceName }};
}}

// 測試
if (require.main === module) {{
  auditContract().then(r => console.log("Audit result:", r)).catch(e => console.error(e));
}}
"#,
        source = payload.source_name,
        risk = payload.risk_score,
        qap = payload.qap_verified,
        risk_level = if payload.risk_score >= 85.0 { "critical" } else if payload.risk_score >= 70.0 { "high" } else if payload.risk_score >= 40.0 { "medium" } else { "low" },
        constraints = payload.r1cs_constraints,
        wires = payload.r1cs_wires,
        risk_int = (payload.risk_score * 10.0) as u64,
        timestamp = payload.timestamp,
    )
}

