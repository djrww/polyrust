/// 完整管線：R1CS -> QAP -> Groth16 -> Solana Ix + JSON
pub fn run_groth16_pipeline(r1cs: &R1cs, qap: &Qap) -> (Groth16Proof, String, String, Vec<u8>) {
    let proof = groth16_from_r1cs(r1cs, qap);
    let json = proof.to_json().to_string();
    let solana_program = generate_solana_groth16_verifier(&proof);
    let ix_data = proof.to_solana_ix_data();
    (proof, json, solana_program, ix_data)
}

